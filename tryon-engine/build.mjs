// Builds the WebView try-on engine into one minified script and writes it into
// the app as a TypeScript string module:
//   src/features/try-on/engine/engineBundle.generated.ts
//
// Run after changing anything in tryon-engine/src or in
// src/features/try-on/core:   cd tryon-engine && npm run build
import { build } from 'esbuild';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, '../src/features/try-on/engine/engineBundle.generated.ts');

const result = await build({
  entryPoints: [resolve(here, 'src/main.tsx')],
  bundle: true,
  minify: true,
  format: 'iife',
  // WKWebView on iOS 15+ and Android System WebView; both run ES2020.
  target: ['es2020', 'safari15'],
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
  // The engine imports shared core from ../src; resolve its packages here.
  nodePaths: [resolve(here, 'node_modules')],
  write: false,
  legalComments: 'none',
  logLevel: 'warning',
});

const js = result.outputFiles[0].text;
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  '/* eslint-disable */\n' +
    '// GENERATED by tryon-engine/build.mjs — do not edit. Rebuild with\n' +
    '// `cd tryon-engine && npm run build`.\n' +
    `export const ENGINE_JS = ${JSON.stringify(js)};\n`,
);
console.log(`engine bundle: ${(js.length / 1024).toFixed(0)} KB → ${outFile}`);
